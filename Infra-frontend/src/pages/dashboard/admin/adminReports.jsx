import { useState } from "react";
import { useNavigate, useSearchParams } from "react-router-dom";
import { toast } from "react-toastify";

import PageHeader from "../../../components/dashboard/shared/PageHeader";
import { findAdminItem } from "../../../components/dashboard/sidebar/sidebarConfig";
import SeverityBadge from "../../../components/analysis/SeverityBadge";
import AiSimulatedBanner from "../../../components/admin/AiSimulatedBanner";
import DataTable from "../../../components/admin/DataTable";
import Pagination from "../../../components/admin/Pagination";
import StatusChip from "../../../components/admin/StatusChip";
import { DateRangeFilter, FilterSelect } from "../../../components/admin/AdminFilters";

import { downloadAdminReport, getAdminReports, getManagedUsers } from "../../../api/adminApi";
import { useAdminList } from "../../../utils/useAdminList";
import { useListOptions } from "../../../utils/useListOptions";
import { useProjectOptions } from "../../../utils/useProjectOptions";
import { useTeamOptions } from "../../../utils/useTeamOptions";
import { getDownloadErrorMessage, saveBlob } from "../../../utils/fileDownload";
import { formatDate, paramsToFilters, withDateRange } from "../../../utils/adminFormat";

const FILTER_KEYS = ["status", "project", "team", "generatedBy"];
const USER_PARAMS = { sort: "name" };

const fetchReports = (params) => getAdminReports(withDateRange(params));

const AdminReportsPage = () => {
    const navigate = useNavigate();
    const [params] = useSearchParams();

    const { items, pagination, extra, loading, error, filters, setFilter } = useAdminList(
        fetchReports,
        paramsToFilters(params, FILTER_KEYS)
    );

    const { projects } = useProjectOptions();
    const { teams } = useTeamOptions();
    const { items: users } = useListOptions(getManagedUsers, USER_PARAMS);

    const [downloadingId, setDownloadingId] = useState(null);

    const handleDownload = async (report) => {
        setDownloadingId(report._id);

        try {
            const res = await downloadAdminReport(report._id);
            saveBlob(res.data, report.fileName || `${report.reportCode}.pdf`);
        } catch (err) {
            toast.error(await getDownloadErrorMessage(err, "Failed to download report."));
        } finally {
            setDownloadingId(null);
        }
    };

    const columns = [
        {
            key: "report",
            header: "Report",
            render: (row) => (
                <div>
                    <strong>{row.reportCode}</strong>
                    <div className="adm-subtext">v{row.version || 1}</div>
                </div>
            ),
        },
        {
            key: "project",
            header: "Project",
            render: (row) => (
                <div>
                    {row.inspection?.project?.name || "-"}
                    <div className="adm-subtext">{row.inspection?.project?.projectCode}</div>
                </div>
            ),
        },
        { key: "inspection", header: "Inspection", render: (row) => row.inspection?.inspectionCode || "-" },
        {
            key: "analysis",
            header: "Analysis",
            render: (row) => (
                <div>
                    {row.analysis?.analysisCode || "-"}
                    {row.analysis?.overallSeverity && (
                        <div>
                            <SeverityBadge severity={row.analysis.overallSeverity} />
                        </div>
                    )}
                </div>
            ),
        },
        { key: "team", header: "Team", render: (row) => row.inspection?.project?.team?.name || "-" },
        { key: "generatedBy", header: "Generated by", render: (row) => row.generatedBy?.name || "-" },
        { key: "status", header: "Status", render: (row) => <StatusChip value={row.status || "Final"} /> },
        { key: "generatedAt", header: "Generated", render: (row) => formatDate(row.generatedAt) },
        {
            key: "actions",
            header: "",
            render: (row) => (
                <button
                    type="button"
                    className="btn-outline btn-sm"
                    disabled={downloadingId === row._id}
                    onClick={(event) => {
                        event.stopPropagation();
                        handleDownload(row);
                    }}
                >
                    {downloadingId === row._id ? "Downloading..." : "Download"}
                </button>
            ),
        },
    ];

    return (
        <div className="adm-page">
            <PageHeader title="Reports" subtitle={findAdminItem("reports")?.description} />

            <AiSimulatedBanner aiMode={extra?.aiMode} disclaimer={extra?.aiDisclaimer} />

            <div className="adm-toolbar">
                <input
                    className="input"
                    placeholder="Search by report code or file name"
                    value={filters.search}
                    onChange={(event) => setFilter("search", event.target.value)}
                />

                <FilterSelect
                    value={filters.status}
                    onChange={(v) => setFilter("status", v)}
                    allLabel="All statuses"
                    options={["Final", "Draft"]}
                />
                <FilterSelect
                    value={filters.project}
                    onChange={(v) => setFilter("project", v)}
                    allLabel="All projects"
                    options={projects.map((p) => ({ value: p._id, label: `${p.projectCode} · ${p.name}` }))}
                />
                <FilterSelect
                    value={filters.team}
                    onChange={(v) => setFilter("team", v)}
                    allLabel="All teams"
                    options={teams.map((t) => ({ value: t._id, label: t.name }))}
                />
                <FilterSelect
                    value={filters.generatedBy}
                    onChange={(v) => setFilter("generatedBy", v)}
                    allLabel="Generated by anyone"
                    options={users.map((u) => ({ value: u._id, label: `${u.name} (${u.role})` }))}
                />

                <DateRangeFilter from={filters.from} to={filters.to} onChange={setFilter} />

                <FilterSelect
                    value={filters.sort}
                    onChange={(v) => setFilter("sort", v)}
                    allLabel="Newest first"
                    options={[{ value: "oldest", label: "Oldest first" }]}
                />
            </div>

            <DataTable
                columns={columns}
                rows={items}
                loading={loading}
                error={error}
                emptyText="No reports found."
                onRowClick={(row) => navigate(`/dashboard/admin/reports/${row._id}`)}
            />

            <Pagination pagination={pagination} onPageChange={(page) => setFilter("page", page)} />
        </div>
    );
};

export default AdminReportsPage;