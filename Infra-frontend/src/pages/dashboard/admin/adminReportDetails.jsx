import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { toast } from "react-toastify";
import { FontAwesomeIcon } from "@fortawesome/react-fontawesome";
import { faChevronLeft } from "@fortawesome/free-solid-svg-icons";

import PageHeader from "../../../components/dashboard/shared/PageHeader";
import { Card, Chip, Row } from "../../../components/dashboard/shared/DetailsKit";
import AiSimulatedBanner from "../../../components/admin/AiSimulatedBanner";

import ReportStatusBadge from "../../../components/reports/reportStatusBadge";
import ReportSummary from "../../../components/reports/reportSummary";
import ReportProjectInfo from "../../../components/reports/reportProjectInfo";
import ReportInspectionInfo from "../../../components/reports/reportInspectionInfo";
import ReportAnalysisSummary from "../../../components/reports/reportAnalysisSummary";
import ReportCrackTable from "../../../components/reports/reportCrackTable";
import ReportRecommendations from "../../../components/reports/reportRecommendations";

import { downloadAdminReport, getAdminReport } from "../../../api/adminApi";
import { getApiErrorMessage } from "../../../api/authApi";
import { getDownloadErrorMessage, saveBlob } from "../../../utils/fileDownload";
import { formatDateTime } from "../../../utils/adminFormat";

const AdminReportDetailsPage = () => {
    const { id } = useParams();

    const [data, setData] = useState(null);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState("");
    const [downloading, setDownloading] = useState(false);

    useEffect(() => {
        let cancelled = false;

        const run = async () => {
            try {
                const res = await getAdminReport(id);
                if (!cancelled) setData(res.data);
            } catch (err) {
                if (!cancelled) setError(getApiErrorMessage(err, "Failed to load report."));
            } finally {
                if (!cancelled) setLoading(false);
            }
        };

        run();
        return () => {
            cancelled = true;
        };
    }, [id]);

    if (loading) return <div className="page-loading">Loading report details...</div>;
    if (error || !data) return <div className="page-loading">{error || "Report not found."}</div>;

    const { report, cracks = [] } = data;
    const { reportCode, status, inspection, analysis, recommendations = [] } = report;
    const project = inspection?.project;
    const team = project?.team;

    const handleDownload = async () => {
        setDownloading(true);

        try {
            const res = await downloadAdminReport(report._id);
            saveBlob(res.data, report.fileName || `${reportCode}.pdf`);
        } catch (err) {
            toast.error(await getDownloadErrorMessage(err, "Failed to download report."));
        } finally {
            setDownloading(false);
        }
    };

    return (
        <div className="report-details-page">
            <Link to="/dashboard/admin/reports" className="dtl-back">
                <FontAwesomeIcon icon={faChevronLeft} />
                All reports
            </Link>

            <div className="report-details-header">
                <PageHeader
                    title="Inspection Report"
                    subtitle={`${reportCode} • ${project?.name || "Unnamed Project"}`}
                />

                <div className="report-details-header-actions">
                    <ReportStatusBadge status={status} />

                    <button
                        type="button"
                        className="report-export-button"
                        onClick={handleDownload}
                        disabled={downloading}
                    >
                        {downloading ? "Downloading..." : "Download PDF"}
                    </button>
                </div>
            </div>

            <AiSimulatedBanner aiMode={data.aiMode} disclaimer={data.aiDisclaimer} />

            <ReportSummary report={report} analysis={analysis} />
            <ReportProjectInfo project={project} />
            <ReportInspectionInfo inspection={inspection} />
            <ReportAnalysisSummary analysis={analysis} cracks={cracks} />
            <ReportCrackTable cracks={cracks} />
            <ReportRecommendations recommendations={recommendations} />

            <div className="dtl">
                <Card title="Report record">
                    <dl className="dtl-rows">
                        <Row label="Generated by">
                            {report.generatedBy
                                ? `${report.generatedBy.name} (${report.generatedBy.role})`
                                : null}
                        </Row>
                        <Row label="Generated on">{formatDateTime(report.generatedAt)}</Row>
                        <Row label="Version">{`v${report.version || 1}`}</Row>
                        <Row label="File name">{report.fileName}</Row>
                        <Row label="Mode">
                            <Chip tone={report.isSimulated ? "warning" : "success"}>
                                {report.isSimulated ? "Simulated" : "Real"}
                            </Chip>
                        </Row>
                        <Row label="Team">
                            {team ? (
                                <Link to={`/dashboard/admin/teams/${team._id}`} className="dtl-link">
                                    {team.name}
                                </Link>
                            ) : null}
                        </Row>
                        <Row label="Inspection">
                            {inspection?._id ? (
                                <Link to={`/dashboard/admin/inspections/${inspection._id}`} className="dtl-link">
                                    {inspection.inspectionCode}
                                </Link>
                            ) : null}
                        </Row>
                        <Row label="Analysis">
                            {analysis?._id ? (
                                <Link to={`/dashboard/admin/analyses/${analysis._id}`} className="dtl-link">
                                    {analysis.analysisCode}
                                </Link>
                            ) : null}
                        </Row>
                    </dl>
                </Card>
            </div>
        </div>
    );
};

export default AdminReportDetailsPage;