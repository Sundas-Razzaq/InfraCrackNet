import DataTable from "./DataTable";
import StatusChip from "./StatusChip";
import { formatDateTime } from "../../utils/adminFormat";

const columns = [
    {
        key: "reportCode",
        header: "Report",
        render: (report) => (
            <div>
                <strong>{report.reportCode}</strong>
                <div className="adm-subtext">v{report.version || 1}</div>
            </div>
        ),
    },
    { key: "status", header: "Status", render: (report) => <StatusChip value={report.status || "Final"} /> },
    { key: "generatedBy", header: "Generated by", render: (report) => report.generatedBy?.name || "-" },
    { key: "generatedAt", header: "Generated", render: (report) => formatDateTime(report.generatedAt) },
];

const LinkedReportsTable = ({ reports = [], onRowClick }) => (
    <DataTable
        bare
        columns={columns}
        rows={reports}
        emptyText="No reports generated yet."
        onRowClick={onRowClick}
    />
);

export default LinkedReportsTable;